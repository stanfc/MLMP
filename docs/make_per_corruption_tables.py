"""Per-corruption R150 tables (one per dataset x all methods) -> docs/per_corruption_R150_tables.md. Re-runnable."""
import os, re
os.chdir("/home/stanfc/TTA-on-OVSS/MLMP")
SETS = [("ACDC", "ACDCDataset"), ("Cityscapes-C", "CityscapesDataset"), ("VOC20-C", "PascalVOC20Dataset"), ("VOC21-C", "PascalVOC21Dataset"),
        ("PC59-C", "PascalContext59Dataset"), ("PC60-C", "PascalContext60Dataset"), ("COCO-Stuff-C", "COCOStuffDataset"), ("COCO-Object-C", "COCOObjectDataset")]
STD = {"TENT": "tent_continual", "SAR": "sar_continual", "SPA": "spa_continual", "TRIBE": "tribe_continual", "DeYO": "deyo_continual",
       "ViDA": "vida_continual", "PTTA": "ptta_continual", "COME": "come_continual", "MGP": "mgp_deyo_mlmp_continual", "DAF": "daf_mlmp_continual"}
ORDER = ["No-Adapt", "MLMP-episodic", "TENT", "SAR", "SPA", "TRIBE", "DeYO", "ViDA", "PTTA", "COME", "MGP", "DAF", "RDumb", "CAGA"]
def find(root, base):
    for s in (f"{base}_15corr_sub100", f"{base}_sub100_15corr", base):
        if os.path.isdir(f"{root}/{s}"): return f"{root}/{s}"
def last_round(p, need150=True):
    if not p or not os.path.exists(p + "/results_all_rounds.txt"): return None
    hdr, rows = None, {}
    for l in open(p + "/results_all_rounds.txt"):
        if l.startswith("Round,"): hdr = [x.strip() for x in l.split(",")[1:]]
        elif l.startswith("Round "):
            q = [x.strip() for x in l.split(",")]
            try: rows[int(q[0].split()[1])] = [float(x) for x in q[1:]]
            except ValueError: pass
    if not rows or (need150 and 150 not in rows): return None
    r = max(rows); return dict(zip(hdr, rows[r]))
def episodic(p):
    if not p or not os.path.exists(p + "/results.txt"): return None
    d = {}
    for l in list(open(p + "/results.txt"))[1:]:
        q = l.split(",")
        try: d[q[0].strip()] = float(q[1].split("+/-")[0])
        except (ValueError, IndexError): pass
    if d: d["Mean_mIoU"] = sum(d.values()) / len(d)
    return d or None
out = ["# Per-corruption mIoU at round 150 (all methods, all benchmarks)\n",
       "Generated by `/home/stanfc/TTA-on-OVSS/MLMP/docs/make_per_corruption_tables.py` from each run's `results_all_rounds.txt` (row of round 150; ACDC = real conditions, others = ImageNet-C severity 5). "
       "Single seed (seed 0), no +/- std. **Bold** = best per row. No-Adapt is the source model; MLMP-episodic = reset every sample (steps=1, lr 1e-3, single pass). "
       "Average = mean over the listed corruptions. CoTTA excluded. RDumb (TENT + full reset to source every 1000 images) column appears only once its 150-round run is complete (`n/a` = not finished).\n"]
for title, folder in SETS:
    root = f"save/{folder}"; acdc = folder == "ACDCDataset"
    cols = {}
    if acdc:
        cols["No-Adapt"] = last_round(f"{root}/naclip_no_adapt", False); cols["MLMP-episodic"] = episodic(f"{root}/naclip_mlmp_episodic")
        for k, v in STD.items(): cols[k] = last_round(f"{root}/naclip_tent_continual" if k == "TENT" else f"{root}/{v}")
        cols["CAGA"] = last_round(f"{root}/adagate_hgate")
    else:
        cols["No-Adapt"] = last_round(find(root, "no_adapt"), False); cols["MLMP-episodic"] = episodic(find(root, "mlmp_episodic"))
        for k, v in STD.items(): cols[k] = last_round(find(root, v))
        cols["CAGA"] = last_round(find(root, "adagate_hgate"))
    cols["RDumb"] = last_round(f"{root}/rdumb_continual")
    names = [k for k in ORDER if k in cols and (cols[k] is not None or k == "RDumb")]
    conds = [c for c in cols["CAGA"] if c != "Mean_mIoU"]
    out.append(f"\n## {title}\n")
    out.append("| Corruption | " + " | ".join(names) + " |"); out.append("|---|" + "---|" * len(names))
    def row(label, key):
        vals = [(cols[n] or {}).get(key) for n in names]
        good = [v for v in vals if v is not None]; best = max(good) if good else None
        cells = ["n/a" if v is None else (f"**{v:.2f}**" if v == best else f"{v:.2f}") for v in vals]
        return f"| {label} | " + " | ".join(cells) + " |"
    for c in conds: out.append(row(c.replace("_", " "), c))
    out.append(row("**Average**", "Mean_mIoU"))
open("docs/per_corruption_R150_tables.md", "w").write("\n".join(out) + "\n")
print("\n".join(out[:20]))
